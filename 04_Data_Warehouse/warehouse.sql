-- project_dw: star schema from the Phase 1 data dictionary.
-- Dimensions use surrogate keys; every dimension has an 'Unknown' row with key -1.
CREATE SCHEMA IF NOT EXISTS project_dw;

----------------------------------------------------------------------
-- Dimensions
----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_dw.dim_date (
 date_key INT PRIMARY KEY,
 full_date DATE NOT NULL UNIQUE,
 day_of_month INT NOT NULL,
 day_name TEXT NOT NULL,
 day_of_week INT NOT NULL,
 week_of_year INT NOT NULL,
 month INT NOT NULL,
 month_name TEXT NOT NULL,
 quarter INT NOT NULL,
 year INT NOT NULL,
 year_month TEXT NOT NULL,
 is_weekend BOOLEAN NOT NULL,
 is_trading_day BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS project_dw.dim_sector (
 sector_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sector_code TEXT NOT NULL UNIQUE,
 sector_name TEXT NOT NULL,
 sector_group TEXT NOT NULL,
 legacy_codes TEXT
);

CREATE TABLE IF NOT EXISTS project_dw.dim_stock (
 stock_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 symbol TEXT NOT NULL,
 company_name TEXT NOT NULL,
 sector_key INT NOT NULL REFERENCES project_dw.dim_sector (sector_key),
 first_trade_date DATE,
 last_trade_date DATE,
 is_active BOOLEAN NOT NULL,
 effective_from DATE,
 effective_to DATE,
 is_current BOOLEAN NOT NULL
);
-- only one current version per symbol
CREATE UNIQUE INDEX IF NOT EXISTS ux_dim_stock_current ON project_dw.dim_stock (symbol) WHERE is_current;

CREATE TABLE IF NOT EXISTS project_dw.dim_risk_tier (
 risk_tier_key INT PRIMARY KEY,
 tier_name TEXT NOT NULL UNIQUE,
 percentile_min NUMERIC(4,2),
 percentile_max NUMERIC(4,2),
 tier_description TEXT NOT NULL,
 sort_order INT NOT NULL
);

CREATE TABLE IF NOT EXISTS project_dw.dim_event_type (
 event_type_key INT PRIMARY KEY,
 event_type_code TEXT NOT NULL UNIQUE,
 event_type_name TEXT NOT NULL,
 event_category TEXT NOT NULL,
 detection_rule TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS project_dw.dim_policy_action (
 policy_action_key INT PRIMARY KEY,
 action_name TEXT NOT NULL UNIQUE,
 action_description TEXT NOT NULL
);

----------------------------------------------------------------------
-- Facts
----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS project_dw.fact_daily_stock_price (
 date_key INT NOT NULL REFERENCES project_dw.dim_date (date_key),
 stock_key INT NOT NULL REFERENCES project_dw.dim_stock (stock_key),
 risk_tier_key INT NOT NULL REFERENCES project_dw.dim_risk_tier (risk_tier_key),
 open_price NUMERIC(12,4),
 high_price NUMERIC(12,4),
 low_price NUMERIC(12,4),
 close_price NUMERIC(12,4) NOT NULL,
 ldcp NUMERIC(12,4),
 volume BIGINT NOT NULL,
 daily_log_return DOUBLE PRECISION,
 price_range_pct DOUBLE PRECISION,
 volatility_20d DOUBLE PRECISION,
 volatility_60d DOUBLE PRECISION,
 avg_volume_20d DOUBLE PRECISION,
 risk_percentile DOUBLE PRECISION,
 is_traded BOOLEAN NOT NULL,
 is_ohlc_valid BOOLEAN,
 load_timestamp TIMESTAMP NOT NULL DEFAULT now(),
 PRIMARY KEY (date_key, stock_key)
);

CREATE TABLE IF NOT EXISTS project_dw.fact_market_daily (
 date_key INT PRIMARY KEY REFERENCES project_dw.dim_date (date_key),
 stocks_listed INT NOT NULL,
 stocks_traded INT NOT NULL,
 advancers INT NOT NULL,
 decliners INT NOT NULL,
 total_volume BIGINT NOT NULL,
 market_return DOUBLE PRECISION,
 market_volatility_20d DOUBLE PRECISION,
 median_stock_volatility_20d DOUBLE PRECISION,
 pct_stocks_high_risk DOUBLE PRECISION,
 load_timestamp TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS project_dw.fact_sector_daily (
 date_key INT NOT NULL REFERENCES project_dw.dim_date (date_key),
 sector_key INT NOT NULL REFERENCES project_dw.dim_sector (sector_key),
 stocks_traded INT NOT NULL,
 sector_volume BIGINT NOT NULL,
 avg_return DOUBLE PRECISION,
 avg_volatility_20d DOUBLE PRECISION,
 pct_high_risk DOUBLE PRECISION,
 load_timestamp TIMESTAMP NOT NULL DEFAULT now(),
 PRIMARY KEY (date_key, sector_key)
);

CREATE TABLE IF NOT EXISTS project_dw.fact_policy_decision (
 date_key INT PRIMARY KEY REFERENCES project_dw.dim_date (date_key),
 policy_action_key INT NOT NULL REFERENCES project_dw.dim_policy_action (policy_action_key),
 policy_rate_pct NUMERIC(5,2) NOT NULL,
 previous_rate_pct NUMERIC(5,2),
 change_bps INT NOT NULL,
 load_timestamp TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS project_dw.fact_market_event (
 date_key INT NOT NULL REFERENCES project_dw.dim_date (date_key),
 stock_key INT NOT NULL REFERENCES project_dw.dim_stock (stock_key),
 event_type_key INT NOT NULL REFERENCES project_dw.dim_event_type (event_type_key),
 load_timestamp TIMESTAMP NOT NULL DEFAULT now(),
 PRIMARY KEY (date_key, stock_key, event_type_key)
);
